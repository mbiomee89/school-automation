/** Dedupe while preserving first-occurrence order (Saudi, Palestine stay first). */
export const COUNTRY_OR_NATIONALITY_OPTIONS: string[] = (() => {
  const seen = new Set<string>()
  const out: string[] = []
  for (const c of COUNTRIES_AR) {
    if (seen.has(c)) continue
    seen.add(c)
    out.push(c)
  }
  return out
})()

export function countrySelectOptions(current: string): string[] {
  const list = [...COUNTRY_OR_NATIONALITY_OPTIONS]
  if (current && !list.includes(current)) list.push(current)
  return list
}
